    @Test fun nativeScalarsContainersAndUnsignedGoldenBytesMatchFallback() {
        assertTrue(NativeMedia.available)
        val values = listOf(false, true, 0.toByte(), 256.toShort(), 65536, 1L shl 40, Long.MAX_VALUE,
            -1, Long.MIN_VALUE, 1.25f, -0.0f, Float.NaN, Double.POSITIVE_INFINITY, Double.NaN,
            BigInteger.ZERO, BigInteger.valueOf(65536), BigInteger.ONE.shiftLeft(40), BigInteger.ONE.shiftLeft(63),
            BigInteger.ONE.shiftLeft(64).subtract(BigInteger.ONE), "", "name\u0000😀", byteArrayOf(0, -1),
            listOf(1, "two", false), linkedMapOf<Any?, Any>(null to 1, 3 to "three", "nested" to listOf(mapOf("type" to 110))),
            mapOf("picture" to ByteArray(500_000) { 7 }))
        for (value in values) {
            val expected = BplistCodec.encodeFallback(value)
            val actual = BplistCodec.encode(value)
            assertArrayEquals(expected, actual)
            assertValue(BplistCodec.decodeFallback(expected), BplistCodec.decode(actual))
        }
    }

    @Test fun platformUnicodeReplacementKeepsNulBomPairsAndMalformedSurrogates() {
        assertTrue(NativeMedia.available)
        for (value in listOf("\u0000", "A\u0000😀B", "\ufeffA", "\ud800", "\udc00", "\ud800A", "\udc00A", "\ud800\ud801", "\ud800\ufeff")) {
            val expected = BplistCodec.encodeFallback(value)
            assertArrayEquals(expected, BplistCodec.encode(value))
            assertValue(BplistCodec.decodeFallback(expected), BplistCodec.decode(expected))
        }
        for (objectBytes in listOf(byteArrayOf(0x53, 0, -128, -1),
            byteArrayOf(0x62, 0xd8.toByte(), 0, 0, 65), byteArrayOf(0x62, 0xdc.toByte(), 0, 0, 65),
            byteArrayOf(0x62, 0xd8.toByte(), 0, 0xd8.toByte(), 1), byteArrayOf(0x62, -2, -1, 0, 0),
            byteArrayOf(0x63, 0xd8.toByte(), 0, 0, 0, -2, -1))) {
            val encoded = plist(listOf(objectBytes))
            assertValue(BplistCodec.decodeFallback(encoded), BplistCodec.decode(encoded))
        }
    }

    @Test fun decodedNullFloatDoubleUidSetDateAndDuplicateKeysKeepTheirJavaTypes() {
        assertTrue(NativeMedia.available)
        val objects = listOf(byteArrayOf(0), byteArrayOf(0x22) + intBytes(1.25f.toRawBits()),
            byteArrayOf(0x23) + longBytes((-0.0).toRawBits()), byteArrayOf(0x87.toByte()) + longBytes(-1)) +
            listOf(0.0, -978307200.0005, Double.NaN, Double.POSITIVE_INFINITY, Double.NEGATIVE_INFINITY).map {
                byteArrayOf(0x30) + longBytes(it.toRawBits())
            }
        for (objectBytes in objects) {
            val encoded = plist(listOf(objectBytes))
            assertValue(BplistCodec.decodeFallback(encoded), BplistCodec.decode(encoded))
        }
        for (encoded in listOf(plist(listOf(byteArrayOf(0xc2.toByte(), 1, 1), byteArrayOf(9))),
            plist(listOf(byteArrayOf(0xd2.toByte(), 1, 1, 2, 3), byteArrayOf(0x51, 65), byteArrayOf(8), byteArrayOf(9))))) {
            assertValue(BplistCodec.decodeFallback(encoded), BplistCodec.decode(encoded))
        }
        // Safari insertPlayQueueItem's nested Start-Date, generated by Python plistlib.
        val safariHex = "62706c6973743030d201020308546974656d5474797065d2040506075f1010436f6e74656e742d4c6f636174696f6e" +
            "5a53746172742d446174655f101968747470733a2f2f6578616d706c652e636f6d2f762e6d70343341c83698a00000005f1013" +
            "696e73657274506c617951756575654974656d080d12171c2f3a565f000000000000010100000000000000090000000000000000" +
            "0000000000000075"
        val safari = safariHex.chunked(2).map { it.toInt(16).toByte() }.toByteArray()
        assertValue(BplistCodec.decodeFallback(safari), BplistCodec.decode(safari))
        assertEquals(Date(1_790_769_600_000L), ((BplistCodec.decode(safari) as Map<*, *>)["item"] as Map<*, *>)["Start-Date"])
    }

    @Test fun nativeMalformedHeadersAndExpansionBudgetsKeepExceptionMessages() {
        assertTrue(NativeMedia.available)
        val good = plist(listOf(byteArrayOf(9)))
        val cases = listOf(ByteArray(0), good.copyOf().apply { this[0] = 0 },
            good.copyOf().apply { this[size - 26] = 0 }, good.copyOf().apply { this[size - 25] = 9 },
            good.copyOf().apply { longBytes(-1).copyInto(this, size - 24) },
            good.copyOf().apply { longBytes(7).copyInto(this, size - 8) },
            good.copyOf().apply { intBytes(0).copyInto(this, 9) },
            plist(listOf(byteArrayOf(0x1f))), plist(listOf(byteArrayOf(0x8f.toByte()))),
            plist(listOf(byteArrayOf(0xaf.toByte(), 0x1f))),
            plist(listOf(byteArrayOf(0xd1.toByte(), 1, 2), byteArrayOf(9), byteArrayOf(8))),
            plist(listOf(byteArrayOf(0xa1.toByte(), 0))),
            plist((0 until 30).map { byteArrayOf(0xa2.toByte(), (it + 1).toByte(), (it + 1).toByte()) } + byteArrayOf(9)),
            plist(listOf(counted(0xaf, 100_000, ByteArray(100_000) { 1 }), byteArrayOf(0xa0.toByte()))),
            plist(listOf(counted(0xaf, 1_000_000, ByteArray(1_000_000)))),
            plist(listOf(counted(0xaf, 20_000, ByteArray(20_000) { 1 }), counted(0x4f, 200_000, ByteArray(200_000)))))
        for (encoded in cases) {
            val expected = assertThrows(IllegalArgumentException::class.java) { BplistCodec.decodeFallback(encoded) }
            val actual = assertThrows(IllegalArgumentException::class.java) { BplistCodec.decode(encoded) }
            assertEquals(expected.message, actual.message)
        }
    }

    @Test fun encodingErrorsDepthBoundaryAndPendingJavaExceptionsMatchFallback() {
        assertTrue(NativeMedia.available)
        var nested: Any? = true
        repeat(128) { nested = listOf(nested) }
        assertArrayEquals(BplistCodec.encodeFallback(nested), BplistCodec.encode(nested))
        val cycle = ArrayList<Any?>().apply { add(this) }
        for (value in listOf(null, Date(0), 1.toBigDecimal(), BigInteger.valueOf(-1), BigInteger.ONE.shiftLeft(64), listOf(nested), cycle)) {
            val expected = assertThrows(IllegalArgumentException::class.java) { BplistCodec.encodeFallback(value) }
            val actual = assertThrows(IllegalArgumentException::class.java) { BplistCodec.encode(value) }
            assertEquals(expected.message, actual.message)
        }
        val throwing = object : AbstractList<Any?>() {
            override val size = 1
            override fun get(index: Int): Any? = throw IllegalStateException("plist callback\u0000failed")
        }
        assertEquals("plist callback\u0000failed", assertThrows(IllegalStateException::class.java) { BplistCodec.encode(throwing) }.message)
        val throwingInteger = object : BigInteger("7") {
            override fun toByte(): Byte = 7
            override fun toShort(): Short = 7
            override fun toLong(): Long = throw IllegalStateException("plist BigInteger\u0000failed")
        }
        assertEquals("plist BigInteger\u0000failed", assertThrows(IllegalStateException::class.java) { BplistCodec.encode(throwingInteger) }.message)
    }

    @Test fun wideContainersAndMalformedDictionaryKeysDoNotExhaustJniLocalReferences() {
        assertTrue(NativeMedia.available)
        val value = (0 until 20_000).associate { "key-$it\u0000😀" to it }
        val encoded = BplistCodec.encode(value)
        assertArrayEquals(BplistCodec.encodeFallback(value), encoded)
        assertValue(BplistCodec.decodeFallback(encoded), BplistCodec.decode(encoded))
        val count = 10_000
        val keyRefs = ByteArray(count * 2) { index -> ((index / 2 + 1) ushr (if (index % 2 == 0) 8 else 0)).toByte() }
        val valueRefs = ByteArray(count * 2) { index -> ((count + 1) ushr (if (index % 2 == 0) 8 else 0)).toByte() }
        val dictionary = counted(0xdf, count, keyRefs + valueRefs)
        val malformed = plist(listOf(dictionary) + List(count) { byteArrayOf(0x61, 0xd8.toByte(), 0) } + byteArrayOf(0x10, 7), refSize = 2)
        assertValue(BplistCodec.decodeFallback(malformed), BplistCodec.decode(malformed))
    }

    @Test fun actualAirPlayControlSocketUsesNativePlistsForInfoAndCommands() {
        assertTrue(NativeMedia.available)
        ServerSocket(0, 1, InetAddress.getLoopbackAddress()).use { server ->
            Socket(server.inetAddress, server.localPort).use { client ->
                val config = AirPlayConfig("test\u0000😀", "02:00:00:00:00:02", "02:00:00:00:00:01", "366.0", main = AirPlayDisplayConfig(1280, 720))
                val received = AtomicReference<Map<String, Any?>>()
                val session = AirPlaySession(server.accept(), config, AirPlayIdentity.generate(), PairingStore(), null,
                    object : AirPlaySessionListener {
                        override fun onCommand(session: AirPlaySession, type: String, params: Map<String, Any?>) {
                            if (type == "codec-test") received.set(params)
                        }
                    }, object : AirPlayMediaHandler {})
                try {
                    session.start()
                    client.soTimeout = 5000
                    fun exchange(method: String, path: String, body: ByteArray): ByteArray {
                        client.getOutputStream().apply {
                            write("$method $path RTSP/1.0\r\nCSeq: 1\r\nContent-Length: ${body.size}\r\n\r\n".toByteArray(Charsets.US_ASCII))
                            write(body); flush()
                        }
                        val header = ByteArrayOutputStream()
                        while (!header.toString("US-ASCII").endsWith("\r\n\r\n")) {
                            val byte = client.getInputStream().read()
                            check(byte >= 0); header.write(byte)
                        }
                        val text = header.toString("US-ASCII")
                        assertTrue(text.startsWith("RTSP/1.0 200 OK\r\n"))
                        val length = text.substringAfter("Content-Length: ").substringBefore("\r\n").toInt()
                        return ByteArray(length).also { DataInputStream(client.getInputStream()).readFully(it) }
                    }
                    assertArrayEquals(BplistCodec.encodeFallback(AirPlayInfoPlist.build(config)), exchange("GET", "/info", ByteArray(0)))
                    val params = linkedMapOf("name" to "wire\u0000😀", "data" to byteArrayOf(0, -1), "nested" to listOf(65536, true))
                    exchange("POST", "/command", BplistCodec.encodeFallback(mapOf("type" to "codec-test", "params" to params)))
                    assertValue(BplistCodec.decodeFallback(BplistCodec.encodeFallback(params)), received.get())
                } finally { session.close() }
            }
        }
    }

    private fun longBytes(value: Long) = ByteArray(8) { (value ushr (56 - it * 8)).toByte() }
    private fun intBytes(value: Int) = longBytes(value.toLong()).copyOfRange(4, 8)
    private fun counted(marker: Int, count: Int, payload: ByteArray) = byteArrayOf(marker.toByte(), 0x12) + intBytes(count) + payload

    private fun plist(objects: List<ByteArray>, refSize: Int = 1): ByteArray {
        val out = ByteArrayOutputStream().apply { write("bplist00".toByteArray()) }
        val offsets = ArrayList<Int>()
        for (objectBytes in objects) { offsets.add(out.size()); out.write(objectBytes) }
        val table = out.size()
        for (offset in offsets) out.write(intBytes(offset))
        out.write(ByteArray(32).apply {
            this[6] = 4; this[7] = refSize.toByte()
            longBytes(objects.size.toLong()).copyInto(this, 8)
            longBytes(table.toLong()).copyInto(this, 24)
        })
        return out.toByteArray()
    }

    private fun assertValue(expected: Any?, actual: Any?) {
        when (expected) {
            is ByteArray -> assertArrayEquals(expected, actual as ByteArray)
            is Float -> assertEquals(expected.toRawBits(), (actual as Float).toRawBits())
            is Double -> assertEquals(expected.toRawBits(), (actual as Double).toRawBits())
            is List<*> -> {
                actual as List<*>; assertEquals(expected.size, actual.size)
                expected.zip(actual).forEach { (a, b) -> assertValue(a, b) }
            }
            is Map<*, *> -> {
                actual as Map<*, *>; assertEquals(expected.keys.toList(), actual.keys.toList())
                expected.forEach { (key, value) -> assertValue(value, actual[key]) }
            }
            else -> { assertEquals(expected?.javaClass, actual?.javaClass); assertEquals(expected, actual) }
        }
    }
}
